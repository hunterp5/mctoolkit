"""Generate ``molmanager/chem/depiction_font_metrics.py`` from the bundled label font.

The depiction builder runs in worker processes that must not import Qt, so it
measures atom labels from this table instead of a live font. Re-run after
replacing the font file:

    python scripts/build_font_metrics.py
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT_PATH = ROOT / "molmanager" / "resources" / "fonts" / "LiberationSans-Regular.ttf"
OUT_PATH = ROOT / "molmanager" / "chem" / "depiction_font_metrics.py"

# Printable ASCII and Latin-1, Greek, and the symbols atom labels and annotations use.
CODE_POINTS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + list(range(0x391, 0x3CA))
    + [0x2013, 0x2020, 0x2021, 0x2022, 0x2032, 0x2033, 0x2212]
)

HEADER = '''# This file is part of MolManager.
# Copyright (C) 2026 Hunter Picard
#
# MolManager is free software: you can redistribute it and/or modify
# it under the terms of the GNU General Public License as published by
# the Free Software Foundation, either version 3 of the License, or
# (at your option) any later version.
#
# MolManager is distributed in the hope that it will be useful,
# but WITHOUT ANY WARRANTY; without even the implied warranty of
# MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the
# GNU General Public License for more details.
#
# You should have received a copy of the GNU General Public License
# along with MolManager. If not, see <https://www.gnu.org/licenses/>.

"""Glyph metrics of the bundled atom-label font, in font units.

Generated by ``scripts/build_font_metrics.py``; do not edit by hand. The font is
Liberation Sans (SIL Open Font License 1.1), which has Arial's metrics, the
IUPAC GR-0 recommendation for structure labels.

``GLYPHS`` maps a character to ``(advance, x_min, y_min, x_max, y_max)``, with y
up from the baseline. Divide by ``UNITS_PER_EM`` for lengths in em.
"""
'''


def glyph_rows(font: TTFont) -> list[tuple[str, tuple[int, int, int, int, int]]]:
    """``(character, metrics)`` for every wanted code point the font maps."""
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    glyf = font["glyf"]
    rows = []
    for code in CODE_POINTS:
        name = cmap.get(code)
        if name is None:
            continue
        advance, _lsb = hmtx[name]
        glyph = glyf[name]
        if glyph.numberOfContours == 0:
            box = (0, 0, 0, 0)
        else:
            glyph.recalcBounds(glyf)
            box = (glyph.xMin, glyph.yMin, glyph.xMax, glyph.yMax)
        rows.append((chr(code), (advance, *box)))
    return rows


def _ruff_quoted(text: str) -> str:
    """String literal in Ruff's preferred quotes, so the output needs no reformat."""
    literal = repr(text)
    if literal.startswith('"') or '"' in text:
        return literal
    return f'"{literal[1:-1]}"'


def render_module(font_path: Path) -> str:
    """Source text of the generated metrics module."""
    font = TTFont(font_path)
    os2 = font["OS/2"]
    hhea = font["hhea"]
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()
    rows = glyph_rows(font)
    letters = [m[0] for ch, m in rows if ch.isascii() and ch.isalpha()]
    lines = [
        HEADER,
        f'FONT_FAMILY = "{font["name"].getDebugName(1)}"',
        f'FONT_FILE = "{font_path.name}"',
        f'FONT_SHA256 = "{digest}"',
        f"UNITS_PER_EM = {font['head'].unitsPerEm}",
        f"ASCENT = {hhea.ascent}",
        f"DESCENT = {hhea.descent}",
        f"CAP_HEIGHT = {os2.sCapHeight}",
        f"X_HEIGHT = {os2.sxHeight}",
        "# Characters missing from the table are measured as an average letter.",
        f"FALLBACK_ADVANCE = {round(sum(letters) / len(letters))}",
        "",
        "GLYPHS: dict[str, tuple[int, int, int, int, int]] = {",
    ]
    for ch, metrics in rows:
        lines.append(f"    {_ruff_quoted(ch)}: {metrics},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--font", type=Path, default=FONT_PATH)
    ap.add_argument("--out", type=Path, default=OUT_PATH)
    args = ap.parse_args()
    args.out.write_text(render_module(args.font), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
